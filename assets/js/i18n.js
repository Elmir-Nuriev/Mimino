let currentLanguage = localStorage.getItem('auradelmar_lang') || 'ru';

function t(key, lang = currentLanguage) {
  if (I18N[lang] && I18N[lang][key]) {
    return I18N[lang][key];
  }
  if (I18N['ru'] && I18N['ru'][key]) {
    return I18N['ru'][key];
  }
  return key;
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLanguage = lang;
  localStorage.setItem('auradelmar_lang', lang);

  // Update HTML tag
  document.documentElement.lang = lang;
  document.body.classList.toggle('lang-ka', lang === 'ka');

  // Update all text nodes with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key, lang);
    if (translation !== key) {
      if (translation.includes('<') && translation.includes('>')) {
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key, lang);
    if (translation !== key) {
      el.placeholder = translation;
    }
  });

  // Update titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translation = t(key, lang);
    if (translation !== key) {
      el.title = translation;
    }
  });

  // Update desktop language buttons active state
  document.querySelectorAll('.lang-pill-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Update mobile language buttons active state
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Dispatch custom event for app.js and booking.js
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initI18n() {
  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      setLanguage(targetLang);
    });
  });

  setLanguage(currentLanguage);
}

// Global exposure
window.I18N = I18N;
window.t = t;
window.setLanguage = setLanguage;
window.getCurrentLanguage = () => currentLanguage;

document.addEventListener('DOMContentLoaded', initI18n);
